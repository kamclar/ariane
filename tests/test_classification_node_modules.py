"""Architecture guards for family-specific DAG node modules."""

import ast
from pathlib import Path

from backend.classification_dag.nodes import (
    BioinformaticCriteriaNode,
    ClassificationPolicyNode,
    ClinicalLrCriteriaNode,
    EvidenceInteractionNode,
    ExonCnvCriteriaNode,
    FrequencyCriteriaNode,
    FunctionalCriteriaNode,
    ProteinPs1CriteriaNode,
    Pvs1CriteriaNode,
    ReviewTriageNode,
    SpliceContextNode,
)


NODE_CLASSES = (
    SpliceContextNode,
    FrequencyCriteriaNode,
    ExonCnvCriteriaNode,
    FunctionalCriteriaNode,
    Pvs1CriteriaNode,
    ClinicalLrCriteriaNode,
    ProteinPs1CriteriaNode,
    BioinformaticCriteriaNode,
    EvidenceInteractionNode,
    ClassificationPolicyNode,
    ReviewTriageNode,
)


def test_node_classes_are_owned_by_family_specific_modules():
    assert FrequencyCriteriaNode.__module__.endswith(".nodes.population")
    assert FunctionalCriteriaNode.__module__.endswith(".nodes.functional")
    assert Pvs1CriteriaNode.__module__.endswith(".nodes.pvs1")
    assert ClinicalLrCriteriaNode.__module__.endswith(".nodes.clinical")
    assert BioinformaticCriteriaNode.__module__.endswith(".nodes.bioinformatic")
    assert EvidenceInteractionNode.__module__.endswith(".nodes.policy")
    assert ReviewTriageNode.__module__.endswith(".nodes.review")


def test_node_ids_and_outputs_remain_unique():
    nodes = tuple(node_class() for node_class in NODE_CLASSES)
    assert len({node.id for node in nodes}) == len(nodes)
    provided = [key for node in nodes for key in node.provides]
    assert len(set(provided)) == len(provided)


def test_production_runtime_imports_family_nodes_directly():
    runtime_path = (
        Path(__file__).resolve().parents[1]
        / "backend"
        / "classification_dag"
        / "runtime.py"
    )
    source = runtime_path.read_text(encoding="utf-8")
    assert "from backend.classification_dag.nodes import" in source


def test_rule_modules_do_not_import_network_clients():
    root = Path(__file__).resolve().parents[1]
    modules = list((root / "backend" / "classification_dag" / "nodes").glob("*.py"))
    modules.extend(
        root / "backend" / "modules" / name
        for name in (
            "bp1.py",
            "bp7.py",
            "pp3_bp4.py",
            "pvs1.py",
            "table4.py",
            "table9.py",
        )
    )
    forbidden_roots = {"urllib", "requests", "httpx", "aiohttp"}
    violations = []
    for path in modules:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                names = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = [node.module or ""]
            else:
                continue
            for name in names:
                if name.split(".", 1)[0] in forbidden_roots:
                    violations.append(f"{path.name}:{node.lineno}:{name}")
    assert violations == []
